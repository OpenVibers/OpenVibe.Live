#!/usr/bin/env node
'use strict';
// Write public/css/critical-selectors.json: the style.css selectors a public page's first view uses.
//
//   node scripts/perf/critical-css.js [--base https://openvibe.live] [--settle 9000]
//
// Opens each public route below at a phone and a desktop width in headless Chrome, records CSS rule coverage for
// style.css (CDP CSS.startRuleUsageTracking) after the page settles, maps every used rule back to its selectors with
// server/web/critical-css.js's parser (over the exact text the page loaded), and writes their union. The server builds
// the blocking first-paint subset from it (server/web/critical-css.js). Re-run it after a large change to a public
// page's look; a rule it does not list still arrives with the full style.css, just not before the first paint.
const fs = require('fs');
const path = require('path');
const { launch, sleep } = require('./cdp');
const { parse, splitSelectors, SELECTORS } = require('../../server/web/critical-css');

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i === -1 ? def : args[i + 1]; };
const BASE = String(opt('--base', 'https://openvibe.live')).replace(/\/+$/, '');
const SETTLE = Number(opt('--settle', 9000));
// The public routes people land on from search, links and the home page (signed out).
const ROUTES = ['/', '/content', '/vods', '/clips', '/moments', '/rundown', '/chat', '/search?q=game', '/@iZoR_One', '/vod/5717', '/clip/441', '/pastes', '/docs'];
const WIDTHS = [[412, 900, true], [1366, 900, false]];

async function coverage(url, [width, height, mobile]) {
    const cdp = await launch({ width, height });
    try {
        await cdp.send('Page.enable');
        await cdp.send('DOM.enable');
        await cdp.send('CSS.enable');
        if (mobile) await cdp.send('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 2.6, mobile: true });
        const sheets = new Map();
        cdp.on('CSS.styleSheetAdded', (e) => sheets.set(e.header.styleSheetId, e.header));
        await cdp.send('CSS.startRuleUsageTracking');
        await cdp.send('Page.navigate', { url });
        await sleep(SETTLE);
        const r = await cdp.send('CSS.stopRuleUsageTracking');
        const out = new Set();
        const byId = new Map();
        for (const u of (r.result && r.result.ruleUsage) || []) {
            if (!u.used) continue;
            const h = sheets.get(u.styleSheetId);
            if (!h || !/\/css\/style\.css(\?|$)/.test(h.sourceURL || '')) continue;
            if (!byId.has(u.styleSheetId)) {
                const t = await cdp.send('CSS.getStyleSheetText', { styleSheetId: u.styleSheetId });
                const text = (t.result && t.result.text) || '';
                const rules = [];
                const walk = (list) => { for (const n of list) { if (n.type === 'rule') rules.push(n); else if (n.type === 'block') walk(n.children); } };
                walk(parse(text));
                byId.set(u.styleSheetId, rules);
            }
            // The rule whose text holds this range (coverage ranges are a rule's selector and body).
            const rule = byId.get(u.styleSheetId).find((n) => n.start <= u.startOffset && u.startOffset < n.end);
            if (rule) for (const s of splitSelectors(rule.selector)) out.add(s);
        }
        return out;
    } finally {
        cdp.close();
    }
}

(async () => {
    const all = new Set();
    for (const route of ROUTES) {
        for (const w of WIDTHS) {
            const got = await coverage(BASE + route, w);
            for (const s of got) all.add(s);
            console.log(`${route.padEnd(18)} ${String(w[0]).padStart(4)}px  ${got.size} selectors`);
        }
    }
    const selectors = [...all].sort();
    fs.writeFileSync(SELECTORS, `${JSON.stringify({ _about: 'Generated by scripts/perf/critical-css.js: the style.css selectors a public page\'s first view uses (CDP rule coverage, signed out, phone and desktop widths). server/web/critical-css.js builds the blocking first-paint subset from it.', base: BASE, routes: ROUTES, selectors }, null, 1)}\n`);
    console.log(`${selectors.length} selectors → ${path.relative(process.cwd(), SELECTORS)}`);
    process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
