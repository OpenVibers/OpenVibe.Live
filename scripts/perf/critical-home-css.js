#!/usr/bin/env node
'use strict';
// Write public/css/critical-home.json and critical-home-fx.json: the features/home.css and home-fx.css selectors that
// style what is on the home page's screen before any scroll.
//
//   node scripts/perf/critical-home-css.js [--base https://openvibe.live] [--settle 7000]
//
// Opens "/" at a phone, a tablet, a laptop and a wide desktop width in headless Chrome, twice each: with JavaScript off
// (the server's HTML and its styles, what the first paint shows) and on (after the page settles, with its rails and
// cards drawn). For every selector in home.css it asks the page whether an element it matches is on screen (hover,
// focus and pseudo-elements stripped, so the states of what is on screen count too), and writes the union. The server
// builds the home's blocking first-paint subset of home.css from it (server/web/critical-css.js), and the full file
// follows without blocking. Re-run it after a large change to how the top of the home page looks; a rule it does not
// list still arrives with the full home.css, a moment after the first paint.
const fs = require('fs');
const path = require('path');
const { launch, sleep } = require('./cdp');
const { parse, splitSelectors, HOME_SELECTORS, HOME_FX_SELECTORS } = require('../../server/web/critical-css');
// Each stylesheet measured: how the home page links it, and the list written for it.
const TARGETS = [
    { name: 'features/home.css', link: '/css/features/home.css', out: HOME_SELECTORS },
    { name: 'home-fx.css', link: '/css/home-fx.css', out: HOME_FX_SELECTORS },
];

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i === -1 ? def : args[i + 1]; };
const BASE = String(opt('--base', 'https://openvibe.live')).replace(/\/+$/, '');
const SETTLE = Number(opt('--settle', 7000));
const WIDTHS = [[412, 900, true], [820, 1180, true], [1366, 900, false], [1920, 1080, false]];

// In the page: which of these selectors match an element on screen. A selector the page cannot read is kept.
function onScreen(parts) {
    const strip = (sel) => sel.replace(/::?(?:hover|focus-visible|focus-within|focus|active|visited|before|after|placeholder|marker|selection|backdrop|first-line|first-letter|-webkit-[a-z-]+|-moz-[a-z-]+)(?:\([^()]*\))?/g, '').trim() || '*';
    const seen = (el) => { const r = el.getBoundingClientRect(); return r.bottom > 0 && r.top < innerHeight && r.right > 0 && r.left < innerWidth; };
    const out = [];
    for (const part of parts) {
        let els;
        try { els = document.querySelectorAll(strip(part)); } catch { out.push(part); continue; }
        for (const el of els) { if (seen(el)) { out.push(part); break; } }
    }
    return out;
}

async function measure([width, height, mobile], js, target) {
    const parts = target.parts;
    const cdp = await launch({ width, height });
    try {
        await cdp.send('Page.enable');
        if (mobile) await cdp.send('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 2.6, mobile: true });
        if (!js) await cdp.send('Emulation.setScriptExecutionDisabled', { value: true });
        const loaded = new Promise((r) => cdp.on('Page.loadEventFired', r));
        await cdp.send('Page.navigate', { url: `${BASE}/` });
        await Promise.race([loaded, sleep(30000)]);
        await sleep(js ? SETTLE : 1500);
        if (!parts.length) {
            const href = await cdp.evaluate(`(document.querySelector('link[href*="${target.link}"]') || {}).href || ''`);
            if (!href) throw new Error(`the home page links no ${target.name}`);
            const text = await (await fetch(href)).text();
            const walk = (list) => { for (const n of list) { if (n.type === 'rule') parts.push(...splitSelectors(n.selector)); else if (n.type === 'block') walk(n.children); } };
            walk(parse(text));
        }
        return new Set(await cdp.evaluate(`(${onScreen.toString()})(${JSON.stringify([...new Set(parts)])})`) || []);
    } finally {
        cdp.close();
    }
}

(async () => {
    for (const target of TARGETS) {
        target.parts = [];
        const all = new Set();
        for (const w of WIDTHS) {
            for (const js of [false, true]) {
                const got = await measure(w, js, target);
                for (const s of got) all.add(s);
                console.log(`${target.name} / ${String(w[0]).padStart(4)}px ${js ? 'script on ' : 'script off'} ${got.size} of ${new Set(target.parts).size} selectors on screen`);
            }
        }
        const selectors = [...all].sort();
        fs.writeFileSync(target.out, `${JSON.stringify({ _about: `Generated by scripts/perf/critical-home-css.js: the ${target.name} selectors that style what is on the home page's screen before any scroll (signed out; script off and on; 412, 820, 1366 and 1920 px). server/web/critical-css.js builds the home's blocking first-paint subset of ${target.name} from it.`, base: BASE, widths: WIDTHS.map((w) => w[0]), selectors }, null, 1)}\n`);
        console.log(`${selectors.length} selectors → ${path.relative(process.cwd(), target.out)}`);
    }
    process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
