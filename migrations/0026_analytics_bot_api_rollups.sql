-- phase: expand
-- J3 (2026-11-06): bot API calls are counted at ingest instead of written as one analytics_events row each
-- (openvibe-shared's countBotApiAtIngest, server/analytics/store.js). The counters are the hour's and day's totals
-- by endpoint group, status class and bot family; the shared tracker adds them to analytics_hourly and
-- analytics_daily when it computes those, so a day's api_calls, bot_hits and error_count stay what the raw rows
-- gave before.
-- Expand-only: new tables, the existing analytics tables are unchanged. The runtime role creates none.
CREATE TABLE IF NOT EXISTS analytics_bot_api_hourly (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service text NOT NULL, hour text NOT NULL,
    endpoint_group text NOT NULL, status_class text NOT NULL, bot_family text NOT NULL,
    hits bigint NOT NULL DEFAULT 0,
    UNIQUE (service, hour, endpoint_group, status_class, bot_family)
);
CREATE TABLE IF NOT EXISTS analytics_bot_api_daily (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service text NOT NULL, date text NOT NULL,
    endpoint_group text NOT NULL, status_class text NOT NULL, bot_family text NOT NULL,
    hits bigint NOT NULL DEFAULT 0,
    UNIQUE (service, date, endpoint_group, status_class, bot_family)
);
